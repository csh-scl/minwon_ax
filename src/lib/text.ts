export function normalize(s: string): string {
  return (s || '')
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s]/gu, ' ')
    .replace(/\s+/g, ' ')
    .trim()
}

function stripEnding(token: string): string {
  let t = token
  for (let i = 0; i < 2; i += 1) {
    const next = t.replace(ENDING_RE, '')
    if (next === t || next.length < 2) break
    t = next
  }
  return t
}

/** 질의 → 핵심 토큰 (순서 유지, 중복 제거) */
export function tokenize(s: string): string[] {
  const out: string[] = []
  for (const raw of normalize(s).split(' ')) {
    if (!raw) continue
    const t = stripEnding(raw)
    if (t.length < 2 && !/^\p{Script=Han}$/u.test(t)) continue
    if (STOPWORDS.has(t) || STOPWORDS.has(raw)) continue
    if (!out.includes(t)) out.push(t)
  }
  return out
}

export interface WeightedToken {
  token: string
  weight: number
  origin: string
}

/** 동의어 확장 (원 토큰 1.0, 확장 토큰 0.6) */
export function expandTokens(tokens: string[]): WeightedToken[] {
  const out: WeightedToken[] = []
  const seen = new Set<string>()
  for (const t of tokens) {
    if (!seen.has(t)) {
      out.push({ token: t, weight: 1, origin: t })
      seen.add(t)
    }
    for (const syn of SYNONYMS[t] ?? []) {
      if (seen.has(syn)) continue
      out.push({ token: syn, weight: 0.6, origin: t })
      seen.add(syn)
    }
  }
  return out
}

export function bigrams(s: string): Set<string> {
  const t = normalize(s).replace(/\s+/g, '')
  const set = new Set<string>()
  for (let i = 0; i < t.length - 1; i += 1) set.add(t.slice(i, i + 2))
  return set
}

export function dice(a: Set<string>, b: Set<string>): number {
  if (a.size === 0 || b.size === 0) return 0
  let inter = 0
  for (const x of a) if (b.has(x)) inter += 1
  return (2 * inter) / (a.size + b.size)
}

/** 해요체 문장을 합니다체로 바꾸는 최소 규칙 (초안 생성용) */
export function toFormal(sentence: string): string {
  let s = sentence.trim().replace(/[?!.]+$/g, '')
  const table: [RegExp, string][] = [
    [/났어요$/, '났습니다'],
    [/싶어요$/, '싶습니다'],
    [/궁금해요$/, '궁금합니다'],
    [/궁금합니다$/, '궁금합니다'],
    [/없어요$/, '없습니다'],
    [/있어요$/, '있습니다'],
    [/힘들어요$/, '힘듭니다'],
    [/돼요$/, '됩니다'],
    [/되나요$/, '되는지 궁금합니다'],
    [/인가요$/, '인지 궁금합니다'],
    [/하나요$/, '하는지 궁금합니다'],
    [/할까요$/, '해야 하는지 궁금합니다'],
    [/주세요$/, '주시기 바랍니다'],
    [/해요$/, '합니다'],
    [/예요$/, '입니다'],
    [/이에요$/, '입니다'],
    [/어요$/, '습니다'],
    [/아요$/, '습니다'],
    [/요$/, '습니다'],
  ]
  for (const [re, rep] of table) {
    if (re.test(s)) {
      s = s.replace(re, rep)
      break
    }
  }
  if (!/(다|까)$/.test(s)) s = `${s}에 대해 문의드립니다`
  return `${s}.`
}
